# 基础目录
BASE_DIR = Path("/Users/huangyuelin/项目/南航给的数据、文档/data/processed/manual_labeling_tracks_one_criteria")


def get_all_manual_bids_for_date(date: str) -> Set[int]:
    """获取某日期所有人工标注的批号集合。"""
    if date not in MANUAL_LABELS:
        return set()
    
    all_bids = set()
    for flight_bids in MANUAL_LABELS[date].values():
        all_bids.update(flight_bids)
    return all_bids


def extract_batch_id(filename: str) -> int:
    """从文件名中提取批号。"""
    match = re.match(r"Tracks_(\d+)_", filename)
    if match:
        return int(match.group(1))
    return -1


def filter_uav_tracks():
    """过滤非人工标注的无人机航迹。"""
    print("=" * 70)
    print("过滤非人工标注的无人机航迹")
    print("=" * 70)
    print(f"基础目录: {BASE_DIR}")
    
    total_deleted = 0
    total_kept = 0
    
    # 遍历所有日期目录
    for date_dir in sorted(BASE_DIR.iterdir()):
        if not date_dir.is_dir() or not date_dir.name.isdigit():
            continue
        
        date = date_dir.name
        
        # 1214 没有人工标注数据，保留所有航迹
        if date == "1214":
            print(f"\n日期 {date}: 无人工标注数据，保留所有航迹")
            continue
        
        # 获取该日期的所有人工标注批号
        manual_bids = get_all_manual_bids_for_date(date)
        
        if not manual_bids:
            print(f"\n日期 {date}: 无人工标注数据，保留所有航迹")
            continue
        
        print(f"\n日期 {date}: 人工标注批号 {len(manual_bids)} 个")
        
        deleted_count = 0
        kept_count = 0
        
        # 遍历所有飞行次数目录
        for flight_dir in sorted(date_dir.iterdir()):
            if not flight_dir.is_dir():
                continue
            
            # 跳过合集目录
            if flight_dir.name in ["无人机合集", "其他目标合集"]:
                continue
            
            uav_folder = flight_dir / "无人机"
            if not uav_folder.exists():
                continue
            
            # 遍历无人机文件夹中的所有文件
            for track_file in uav_folder.glob("Tracks_*.txt"):
                batch_id = extract_batch_id(track_file.name)
                
                if batch_id < 0:
                    continue
                
                if batch_id in manual_bids:
                    # 在人工标注列表中，保留
                    kept_count += 1
                else:
                    # 不在人工标注列表中，删除
                    os.remove(track_file)
                    print(f"  [删除] {flight_dir.name}/{track_file.name} (批号 {batch_id} 不在人工标注列表)")
                    deleted_count += 1
        
        print(f"  保留: {kept_count}, 删除: {deleted_count}")
        total_deleted += deleted_count
        total_kept += kept_count
    
    print("\n" + "=" * 70)
    print(f"总计: 保留 {total_kept} 个文件, 删除 {total_deleted} 个文件")
    print("=" * 70)


if __name__ == "__main__":
    filter_uav_tracks()
